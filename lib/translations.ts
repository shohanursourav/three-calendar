export type TranslationKey = keyof typeof TRANSLATIONS.bn;

export function translate(
  lang: Language,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const dictionary = TRANSLATIONS[lang] ?? TRANSLATIONS.bn;
  let value: string = dictionary[key] ?? TRANSLATIONS.bn[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([name, raw]) => {
      const rendered = typeof raw === 'number' ? localizeNumber(raw, lang) : raw;
      value = value.replaceAll(`{${name}}`, String(rendered));
    });
  }
  return value;
}

